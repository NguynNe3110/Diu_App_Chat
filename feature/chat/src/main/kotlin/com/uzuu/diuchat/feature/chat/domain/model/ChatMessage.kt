package com.uzuu.diuchat.feature.chat.domain.model

data class ChatMessage(
    val id: String,
    val conversationId: String,
    val senderId: String,
    val senderName: String,
    val content: String,
    val mood: MoodType,
    val status: MessageStatus,
    val replyToId: String? = null,
    val replyQuote: String? = null,
    val createdAtEpochMs: Long = System.currentTimeMillis(),
    val isFromMe: Boolean = true,
    val mediaType: MessageMediaType = MessageMediaType.TEXT,
    val mediaUri: String? = null,
    val audioDurationMs: Long? = null,
    val audioWaveform: List<Float> = emptyList(),
    val caption: String? = null,
    val isPinned: Boolean = false,
    val reactions: List<MessageReaction> = emptyList(),
    val scheduledForLabel: String? = null,
    val isSealedRevealed: Boolean = false,
    val locationDistanceLabel: String? = null,
)
